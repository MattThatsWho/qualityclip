    public static final int SIZE = 9;
    private final String[] rows;

    Icons(String... rows) {
        this.rows = rows;
    }

    public void draw(GuiGraphicsExtractor g, int x, int y, int color) {
        draw(g, x, y, color, color, 1);
    }

    public void draw(GuiGraphicsExtractor g, int x, int y, int color, int accent) {
        draw(g, x, y, color, accent, 1);
    }

    public void draw(GuiGraphicsExtractor g, int x, int y, int color, int accent, int scale) {
        for (int r = 0; r < rows.length; r++) {
            String row = rows[r];
            for (int c = 0; c < row.length(); c++) {
                char ch = row.charAt(c);
                if (ch == '.') continue;
                int col = ch == '+' ? accent : color;
                g.fill(x + c * scale, y + r * scale, x + (c + 1) * scale, y + (r + 1) * scale, col);
            }
        }
    }
